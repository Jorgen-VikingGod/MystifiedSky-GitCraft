/// Paint `icon` centred in `rect` at `size` points.
pub fn paint(ui: &Ui, rect: Rect, icon: Icon, size: f32, color: Color32) {
    let at = Rect::from_center_size(rect.center(), Vec2::splat(size));
    egui::Image::new(icon.source()).tint(color).paint_at(ui, at);
}

/// A clickable icon of `size` points in a `width` by full-height slot, as in the tabs and status
/// bars. Returns the slot's response.
pub fn slot(ui: &mut Ui, width: f32, icon: Icon, size: f32, color: Color32, hover_color: Color32) -> Response {
    let (rect, response) = ui.allocate_exact_size(Vec2::new(width, ui.available_height()), Sense::click());
    let ink = if response.hovered() { hover_color } else { color };
    paint(ui, rect, icon, size, ink);
    response
}
